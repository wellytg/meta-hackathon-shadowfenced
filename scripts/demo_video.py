"""Record the 3-minute demo: drive the real UI with Playwright, narrate with Piper, mux with ffmpeg.

Usage (server running on 127.0.0.1:8765, demo files generated by scripts/make_files.py):
    python scripts/demo_video.py --eval runs/eval_<date>_final_glimmer.json --voice <path>/en_US-ljspeech-high.onnx

Every number shown on screen comes from the --eval file. Nothing is typed by hand.
"""

from __future__ import annotations

import argparse
import json
import shutil
import subprocess
import sys
import time
import wave
from pathlib import Path

from playwright.sync_api import sync_playwright

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))
from shadowfenced.canary import encodings, make_canary  # noqa: E402

URL = "http://127.0.0.1:8765/"
# Playwright only captures frames when pixels change; a 1px animated dot keeps the video on wall-clock time.
TICKER = ("<div style='position:fixed;right:0;bottom:0;width:2px;height:2px;"
          "animation:sfTick 0.2s steps(2) infinite'></div>"
          "<style>@keyframes sfTick{0%{background:#fff0}100%{background:#fff1}}</style>")
TICKER_JS = ("document.addEventListener('DOMContentLoaded',()=>{document.body.insertAdjacentHTML('beforeend',"
             + repr(TICKER) + ")})")
OUT = ROOT / "runs" / "video"


def pct(x: float) -> str:
    return f"{round(x * 100)}%"


